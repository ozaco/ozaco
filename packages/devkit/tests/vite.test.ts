import { describe, expect, it } from 'bun:test'
import { mkdtempSync, readFileSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

import { ozacoManifest } from '../src/vite'

const manifest = {
  manifest: 'ozaco/2',
  name: 'vite-test',
  version: '0.0.0',
  instance: 'i1',
  errors: {},
  services: [
    {
      name: 'contacts',
      version: '0.0.0',
      actions: [
        {
          id: 'contacts.list',
          service: 'contacts',
          action: 'list',
          kind: 'query',
          route: { method: 'GET', path: '/contacts' },
          input: { plane: 'none', brand: null, contentType: null },
          output: {
            plane: 'value',
            brand: null,
            contentType: 'application/json',
            schema: {
              type: 'object',
              properties: { status: { type: 'string', enum: ['lead', 'active'] } },
            },
          },
          errors: {},
          tags: [],
          options: {},
        },
      ],
    },
  ],
}

/** A node answering the manifest at `/docs/manifest`; `null` = nobody listening. */
const node = () => {
  const server = Bun.serve({
    port: 0,
    fetch: request =>
      new URL(request.url).pathname === '/docs/manifest'
        ? Response.json(manifest)
        : new Response('nope', { status: 404 }),
  })

  return { url: `http://127.0.0.1:${server.port}`, stop: () => server.stop(true) }
}

type Hooks = {
  buildStart: () => Promise<void>
  config: () => { resolve?: { alias?: { find: RegExp; replacement: string }[] } }
}

const hooksOf = (plugin: unknown): Hooks => {
  const raw = plugin as Record<string, unknown>
  const hook = (name: string): unknown => {
    const value = raw[name]

    return typeof value === 'object' && value !== null && 'handler' in value
      ? (value as { handler: unknown }).handler
      : value
  }

  return {
    buildStart: hook('buildStart') as Hooks['buildStart'],
    config: hook('config') as Hooks['config'],
  }
}

describe('devkit — vite manifest plugin', () => {
  it('writes manifest.gen.ts and api.gen.ts from the running node, with the codegen options, and aliases the families', async () => {
    const out = mkdtempSync(join(tmpdir(), 'ozaco-devkit-vite-'))
    const upstream = node()

    try {
      const plugin = ozacoManifest.vite({
        url: upstream.url,
        out,
        pollMs: 0,
        codegen: { readonly: true, enums: true },
      })
      const hooks = hooksOf(plugin)

      await hooks.buildStart.call({})

      const api = readFileSync(join(out, 'api.gen.ts'), 'utf8')
      const written = readFileSync(join(out, 'manifest.gen.ts'), 'utf8')

      expect(api).toContain('export interface Api')
      expect(api).toContain('readonly contacts')
      expect(api).toContain("status: ['lead', 'active']")
      expect(api.startsWith('// Generated by @ozaco/devkit')).toBe(true)
      expect(written).toContain('export const manifest = {')
      expect(written).toContain('"name": "vite-test"')

      const config = hooks.config.call({})
      const aliases = config.resolve?.alias ?? []

      expect(aliases.find(entry => entry.find.test('client:core'))?.replacement).toBe(
        '@ozaco/client',
      )
      expect(aliases.find(entry => entry.find.test('std:result'))?.replacement).toBe(
        '@ozaco/std/$1',
      )
    } finally {
      upstream.stop()
      rmSync(out, { recursive: true, force: true })
    }
  })

  it('a node that is down is fatal only without a previously generated file', async () => {
    const out = mkdtempSync(join(tmpdir(), 'ozaco-devkit-vite-'))

    try {
      const plugin = ozacoManifest.vite({
        url: 'http://127.0.0.1:1',
        out,
        pollMs: 0,
        aliases: false,
      })
      const hooks = hooksOf(plugin)

      await expect(hooks.buildStart.call({})).rejects.toThrow('no manifest')
      expect(hooks.config.call({})).toEqual({})

      // with a file in place the build goes on with it
      const upstream = node()
      const warm = hooksOf(ozacoManifest.vite({ url: upstream.url, out, pollMs: 0 }))

      await warm.buildStart.call({})
      upstream.stop()
      await hooks.buildStart.call({})
      expect(readFileSync(join(out, 'api.gen.ts'), 'utf8')).toContain('export interface Api')
    } finally {
      rmSync(out, { recursive: true, force: true })
    }
  })
})
