import type { GenerateOptions } from 'client:codegen'
import { generate } from 'client:codegen'
import { run } from 'std:effect'
import { isFailure } from 'std:result'

import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'

import type { UnpluginInstance } from 'unplugin'
import { createUnplugin } from 'unplugin'

interface ManifestOptions {
  /** the running node's origin (`http://127.0.0.1:3000`). */
  readonly url: string

  /** the directory `manifest.gen.ts` and `api.gen.ts` are written to (`src/client`). */
  readonly out: string

  /** where the docs plugin is mounted. Default `/docs`. */
  readonly docsPath?: string | undefined

  /** the bearer a node with `Docs.use({ auth })` expects. */
  readonly token?: string | undefined

  /** how often the dev server re-asks (the files change only when the manifest did). Default
   * 4000; `0` turns polling off. */
  readonly pollMs?: number | undefined

  /** what `api.gen.ts` is generated with (`readonly`, `docs`, `enums`, …). */
  readonly codegen?: GenerateOptions | undefined

  /** also alias the devkit specifiers (`client:core`, `std:result`, …) to their packages in the
   * app's vite config. Default on. */
  readonly aliases?: boolean | undefined
}

const DEFAULT_POLL_MS = 4000
const BANNER = '// Generated by @ozaco/devkit (vite) — do not edit.'

/** The families an app may write its imports against; `core` means the package root. */
const FAMILIES: readonly (readonly [string, string])[] = [
  ['std', '@ozaco/std'],
  ['transport', '@ozaco/transport'],
  ['db', '@ozaco/db'],
  ['server', '@ozaco/server'],
  ['client', '@ozaco/client'],
  ['ai', '@ozaco/ai'],
  ['cli', '@ozaco/cli'],
]

/**
 * The `resolve.alias` entries that map the devkit specifiers to their packages BEFORE
 * resolution (vite's SSR environment cannot take a resolved package name back from a plugin,
 * an alias it can). Exact `core` matches come before each family's catch-all.
 */
const aliasesOf = (): { find: RegExp; replacement: string }[] =>
  FAMILIES.flatMap(([family, pkg]) => [
    { find: new RegExp(`^${family}:core$`, 'u'), replacement: pkg },
    { find: new RegExp(`^${family}:(.+)$`, 'u'), replacement: `${pkg}/$1` },
  ])

const read = async (path: string): Promise<string | null> => {
  try {
    return await readFile(path, 'utf8')
  } catch {
    return null
  }
}

/** Fetch the manifest and write both files — only when they would change. Answers whether the
 * node answered; a node that did not is `false` (the caller decides how fatal that is). */
const regenerate = async (options: ManifestOptions): Promise<boolean> => {
  const target = `${options.url.replace(/\/+$/u, '')}${options.docsPath ?? '/docs'}/manifest`
  let manifest: unknown

  try {
    const response = await fetch(target, {
      headers: {
        accept: 'application/json',
        ...(options.token ? { authorization: `Bearer ${options.token}` } : {}),
      },
    })

    if (!response.ok) {
      return false
    }

    manifest = await response.json()
  } catch {
    return false
  }

  const generated = await run(() => generate(manifest, options.codegen))

  if (isFailure(generated)) {
    return false
  }

  const manifestFile = join(options.out, 'manifest.gen.ts')
  const apiFile = join(options.out, 'api.gen.ts')
  const manifestSource = `${BANNER}\nimport type { ManifestDef } from '@ozaco/client'\n\nexport const manifest = ${JSON.stringify(manifest, null, 2)} as unknown as ManifestDef.Manifest\n`
  const apiSource = generated.value.replace(/^\/\/ Generated by [^\n]*\n/u, `${BANNER}\n`)

  await mkdir(options.out, { recursive: true })

  if ((await read(manifestFile)) !== manifestSource) {
    await writeFile(manifestFile, manifestSource)
  }

  if ((await read(apiFile)) !== apiSource) {
    await writeFile(apiFile, apiSource)
  }

  return true
}

/**
 * The ONE thing between a running node and a typed front end — `ozacoManifest.vite({ url, out })`
 * in `vite.config.ts`: at build start it pulls `GET <url><docsPath>/manifest` and writes
 * `manifest.gen.ts` (the pre-fetched manifest `connectClient({ manifest })` takes, so a page
 * load costs no round trip) and `api.gen.ts` (the `Api` type, `@ozaco/client/codegen`) into
 * `out`; the dev server re-asks every `pollMs` and rewrites only when the manifest changed, so a
 * route added mid-session reaches the running app without a restart. A node that is not up is
 * fatal only when there is no previously generated file (a build inside an image where nothing
 * listens keeps the committed one). With `aliases` (default) the devkit specifiers are aliased
 * to their packages too.
 */
const ozacoManifest: UnpluginInstance<ManifestOptions, false> = createUnplugin(
  (options: ManifestOptions) => {
    let timer: ReturnType<typeof setInterval> | null = null

    return {
      name: '@ozaco/devkit:manifest',

      async buildStart() {
        const answered = await regenerate(options)
        const previous = await read(join(options.out, 'api.gen.ts'))

        if (!answered && previous === null) {
          throw new Error(
            `@ozaco/devkit: no manifest at ${options.url} and no previously generated api.gen.ts in ${options.out}`,
          )
        }
      },

      vite: {
        config: () => (options.aliases === false ? {} : { resolve: { alias: aliasesOf() } }),

        configureServer(server: {
          httpServer?: { once(event: 'close', fn: () => void): unknown } | null
        }) {
          const pollMs = options.pollMs ?? DEFAULT_POLL_MS

          if (pollMs <= 0 || timer !== null) {
            return
          }

          timer = setInterval(() => {
            void regenerate(options)
          }, pollMs)

          server.httpServer?.once('close', () => {
            if (timer !== null) {
              clearInterval(timer)
              timer = null
            }
          })
        },
      },
    }
  },
)

export { ozacoManifest }
export type { ManifestOptions }
